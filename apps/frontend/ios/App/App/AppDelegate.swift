/// Bridge view controller that disables the WKWebView's rubber-band scroll.
/// CSS `overscroll-behavior: none` does not suppress the native scroll view
/// bounce, so overscrolling the page exposed the black webview background.
/// Wired up via Main.storyboard (customClass = MainViewController).
class MainViewController: CAPBridgeViewController {
    // Load the configured self-host instance directly (no bundled bootstrap
    // page) so there is no purple flash on launch. The URL is stored by the web
    // app via @capacitor/preferences (UserDefaults key "CapacitorStorage.<key>").
    override func instanceDescriptor() -> InstanceDescriptor {
        let descriptor = super.instanceDescriptor()
        // Respect a CAP_SERVER_URL dev build (descriptor.serverURL already set).
        if descriptor.serverURL == nil {
            let stored = UserDefaults.standard.string(forKey: "CapacitorStorage.instance_url")
            descriptor.serverURL = (stored?.isEmpty == false) ? stored : "https://app.jackpoll.org"
        }
        return descriptor
    }

    override func viewDidLoad() {
        super.viewDidLoad()
        webView?.scrollView.bounces = false
        webView?.scrollView.alwaysBounceVertical = false
        webView?.scrollView.alwaysBounceHorizontal = false
    }
}
